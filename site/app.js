const selector = document.querySelector("#scenario");
const status = document.querySelector("#demo-status");
const matches = document.querySelector("#matches");
const rejections = document.querySelector("#rejections");
const el = (tag, text, className) => {
  const node = document.createElement(tag);
  node.textContent = text;
  if (className) node.className = className;
  return node;
};

function render(scenario) {
  document.querySelector("#request-json").textContent = JSON.stringify(scenario.intent, null, 2);
  matches.replaceChildren();
  rejections.replaceChildren();
  for (const match of scenario.result.matches) {
    const card = el("article", "", "match");
    card.append(el("h4", match.title));
    const price = new Intl.NumberFormat("en", { style: "currency", currency: match.unit_price.currency }).format(match.unit_price.amount / 100);
    card.append(el("p", `${price} · relevance score ${match.score.toFixed(2)}`, "price"));
    const reasons = el("ul", "");
    for (const reason of match.reasons) reasons.append(el("li", reason));
    for (const warning of match.warnings) reasons.append(el("li", warning, "warning"));
    card.append(reasons);
    matches.append(card);
  }
  if (!scenario.result.matches.length) matches.append(el("p", "No product meets these constraints. The grinder exceeds the price limit; the engine suggests trying negotiation.", "empty"));
  for (const rejection of scenario.result.rejected) rejections.append(el("li", `${rejection.item_id}: ${rejection.reasons.join("; ")}`));
  document.querySelector("#rejection-count").textContent = `Why ${scenario.result.rejected.length} products were rejected`;
  document.querySelector("#results-heading").textContent = `${scenario.result.matches.length} matching ${scenario.result.matches.length === 1 ? "product" : "products"}`;
  status.textContent = `${scenario.label}: ${scenario.result.matches.length} matches. Results generated by the Merx engine at build time; relevance scores are not probabilities.`;
  document.querySelector("#demo-results").hidden = false;
}

async function load() {
  try {
    const response = await fetch("scenarios.json");
    if (!response.ok) throw new Error("Scenario data unavailable");
    const scenarios = await response.json();
    selector.replaceChildren(...scenarios.map((scenario) => {
      const option = el("option", scenario.label);
      option.value = scenario.id;
      return option;
    }));
    selector.disabled = false;
    selector.addEventListener("change", () => render(scenarios.find((scenario) => scenario.id === selector.value)));
    render(scenarios[0]);
  } catch {
    status.replaceChildren(el("span", "The examples could not load. You can still run the complete demo locally with the commands below."));
    selector.replaceChildren(el("option", "Examples unavailable"));
  }
}
load();

document.querySelector("#copy").addEventListener("click", async () => {
  const copyStatus = document.querySelector("#copy-status");
  try {
    await navigator.clipboard.writeText(document.querySelector("#commands").textContent);
    copyStatus.textContent = "Commands copied. Paste them into your terminal.";
  } catch {
    copyStatus.textContent = "Copy is unavailable. Select and copy the commands above.";
  }
});
